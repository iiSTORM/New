#!/usr/bin/env node
/**
 * Compiles src/app.jsx and inlines it into index.html.
 *
 * The app used to ship its JSX raw and compile it in the browser with
 * @babel/standalone, which is a 3MB download and a parse-and-compile pass
 * of ~3,800 lines standing between the visitor and the first pixel. Babel
 * runs here instead, once, and the browser gets plain JavaScript.
 *
 * The output is INLINED rather than emitted as a sibling app.js on purpose.
 * raw.githubusercontent.com serves everything as text/plain with
 * X-Content-Type-Options: nosniff, so a separate script file would be
 * refused by the browser. Keeping index.html self-contained means it works
 * however it is opened — GitHub Pages, any static host, or a local file.
 * The compiled JS is about the same size as the JSX it replaces, so
 * inlining costs nothing.
 *
 *   node build/build-frontend.js          rebuild index.html
 *   node build/build-frontend.js --check  verify index.html is current (CI)
 */
const fs = require("fs");
const path = require("path");
const babel = require("@babel/core");

const ROOT = path.join(__dirname, "..");
const SRC = path.join(ROOT, "src", "app.jsx");
const TEMPLATE = path.join(ROOT, "src", "index.template.html");
const OUT = path.join(ROOT, "index.html");
const MARKER = "<!-- BUILD:APP -->";

const BANNER =
  "<!-- Generated by build/build-frontend.js from src/app.jsx and\n" +
  "     src/index.template.html. Do not edit this file by hand: the next\n" +
  "     build will overwrite it. Edit the sources and run `npm run build`. -->";

function build() {
  const template = fs.readFileSync(TEMPLATE, "utf8");
  if (!template.includes(MARKER)) {
    throw new Error(`${TEMPLATE} is missing the ${MARKER} marker`);
  }
  const jsx = fs.readFileSync(SRC, "utf8");

  const { code } = babel.transformSync(jsx, {
    filename: SRC,
    presets: [[require.resolve("@babel/preset-react"), { runtime: "classic" }]],
    // No @babel/preset-env: the browsers that can run this app already
    // support the syntax used, and transpiling further would only add bulk.
    babelrc: false,
    configFile: false,
    compact: false,
    comments: false,
  });

  // A literal </script> anywhere in the compiled output would close the tag
  // early. Nothing currently produces one, but a future string constant
  // easily could, and the failure would be a blank page.
  const safe = code.replace(/<\/script>/gi, "<\\/script>");

  return template.replace(MARKER, `${BANNER}\n<script>\n${safe}\n</script>`);
}

const built = build();

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== built) {
    console.error(
      "index.html is out of date with src/. Run `npm run build` and commit the result."
    );
    process.exit(1);
  }
  console.log("index.html is up to date with src/");
} else {
  fs.writeFileSync(OUT, built);
  const kb = (n) => `${(n / 1024).toFixed(0)}KB`;
  console.log(`Built index.html (${kb(built.length)}) from src/app.jsx (${kb(fs.statSync(SRC).size)})`);
}
